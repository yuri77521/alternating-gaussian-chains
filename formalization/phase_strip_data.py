"""Generate proposed rational boxes for the 32-slab width-derivative proof.

Usage: python phase_strip_data.py PATH_TO_ASSEMBLED_V101 [--output DIR]
The frozen replay's Python routines only propose numbers. The generated Lean
rows prove their inequalities using the verified real-interval operations.
"""
import argparse
from fractions import Fraction as F
from math import ceil, floor, isqrt
from pathlib import Path
import sys


def literal(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f"({x.numerator}/{x.denominator})"


def interval(lo, hi):
    return f"⟨{literal(lo)}, {literal(hi)}⟩"


def outward(lo, hi, d=13):
    scale = 10**d
    return F(floor(lo*scale)-1, scale), F(ceil(hi*scale)+1, scale)


def sqrt_sine(xlo, xhi):
    scale = 10**14
    lower = isqrt(floor((1-xhi*xhi)*scale**2))
    upper = isqrt(floor((1-xlo*xlo)*scale**2))+1
    return interval(F(lower,scale), F(upper,scale))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("assembled", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, str(args.assembled.resolve()/"code"))
    from verify_six_site_strip_thresholds import root_bracket
    from verify_six_site_s9_thresholds import nome_at_width
    from verify_six_site_bifurcation import cosine_box, OMEGA

    knots = []
    boxes = []
    rootext = []
    for i in range(33):
        s = F(8)+F(i,32)
        q = nome_at_width(s)
        qr = outward(q.lo,q.hi)
        data = []
        bounds = []
        for outer in [False,True]:
            a,b = root_bracket(s,outer,digits=8)
            a, b = a-F(1,10**8), b+F(1,10**8)
            xl, xu = cosine_box(OMEGA*a), cosine_box(OMEGA*b)
            xl, xu = outward(xl.lo,xl.hi),outward(xu.lo,xu.hi)
            data.append("⟨"+", ".join([interval(a,b),interval(*xl),interval(*xu)])+"⟩")
            bounds.append((xu[0],xl[1]))
        knots.append(f"def knot{i} : Knot := ⟨{literal(s)}, {interval(*qr)}, {data[0]}, {data[1]}⟩")
        rootext.append(bounds)
    for i in range(32):
        for o,tag in [(0,"c"),(1,"b")]:
            boxes.append(f"def sin{tag}{i} : Cert.Interval := {sqrt_sine(rootext[i][o][0],rootext[i+1][o][1])}")

    def module(name, imports, body):
        dst = args.output/(name+".lean")
        dst.write_text(imports+"\n\n/-! Generated by phase_strip_data.py from the frozen replay. -/\n"
            "namespace GaussianChains.PhaseStrip\n\n"+"\n".join(body)+
            "\n\nend GaussianChains.PhaseStrip\n",encoding="utf-8")
    module("PhaseStripData","import PhaseStripSlabs",knots+[""]+boxes)

    for chunk in range(8):
        rows = ["set_option maxHeartbeats 0","set_option maxRecDepth 100000",""]
        for i in range(4*chunk,4*chunk+4):
            rows.append(f"theorem knot{i}_ok : knot{i}.ok := by decide +kernel")
            rows.append(f"theorem slab{i}_ok : slabCheck knot{i} knot{i+1} sinc{i} sinb{i} := by decide +kernel")
        if chunk == 7:
            rows.append("theorem knot32_ok : knot32.ok := by decide +kernel")
        module(f"PhaseStripPart{chunk}","import PhaseStripData",rows)
    cases = ["open Set", "", "set_option maxHeartbeats 800000 in",
        "/-- Strict bounds for the derivative of the actual critical-floor difference on all 32 closed slabs. -/",
        "theorem phaseWidth_deriv_bounds {s : ℝ} (hs : s ∈ Icc 8 9) :",
        "    0.000209555 < deriv phaseWidth s ∧ deriv phaseWidth s < 0.000734655 := by",
        "  rcases hs with ⟨hlo,hhi⟩"]
    for i in range(32):
        rhs = literal(F(8)+F(i+1,32))
        left = "hlo" if i == 0 else f"h{i-1}"
        if i < 31:
            cases += [f"  by_cases h{i} : s ≤ {rhs}",f"  · apply slabCheck_sound knot{i}_ok knot{i+1}_ok slab{i}_ok",
                f"    norm_num [knot{i},knot{i+1}]", f"    constructor <;> linarith only [{left},h{i}]"]
        else:
            cases += [f"  apply slabCheck_sound knot{i}_ok knot{i+1}_ok slab{i}_ok",
                f"  norm_num [knot{i},knot{i+1}]", f"  constructor <;> linarith only [{left},hhi]"]
    cases += ["",
        "/-- On the whole strip the shifted phase widens strictly, so each",
        "endpoint width is attained uniquely at the corresponding endpoint. -/",
        "theorem phaseWidth_extrema : StrictMonoOn phaseWidth (Icc 8 9) ∧",
        "    ∀ s ∈ Icc (8:ℝ) 9, (phaseWidth 8 ≤ phaseWidth s ∧ phaseWidth s ≤ phaseWidth 9) ∧",
        "      (phaseWidth s = phaseWidth 8 ↔ s=8) ∧ (phaseWidth s = phaseWidth 9 ↔ s=9) := by",
        "  apply phaseWidth_endpoint_extrema_of_positive",
        "  intro s hs",
        "  rw [← (phaseWidth_hasDerivAt hs.1.le hs.2.le).deriv]",
        "  exact lt_trans (by norm_num) (phaseWidth_deriv_bounds (Ioo_subset_Icc_self hs)).1",
        "", "#print axioms phaseWidth_deriv_bounds", "#print axioms phaseWidth_extrema"]
    module("PhaseStripVerified","\n".join(f"import PhaseStripPart{i}" for i in range(8)),cases)


if __name__ == "__main__":
    main()

