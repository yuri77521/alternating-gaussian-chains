"""Extract the archived image-node intervals used in width-22 scalar scores."""

import argparse
from itertools import combinations
from pathlib import Path
import sys


def generate():
    here = Path(__file__).resolve().parent
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(here.parent / "study" / "code"))
    import verify_six_site_s22_block_atlas as atlas

    nodes = atlas.gaussian_nodes()
    gaps = {j - i for i, j in combinations(atlas.WITNESS, 2)} | set(range(1, 6))
    rows = []
    for gap in sorted(gaps):
        tick = gap * atlas.H
        lo, hi = nodes[tick][:2]
        rows.append(f"    ({tick}, ofTicks ({lo}) ({hi}))")
    return (
        "import Point22AtlasIndex\n\n"
        "/-! Raw value nodes used by the witness and the internal block sums. "
        "Generated by point22_score_nodes.py. -/\n"
        "namespace GaussianChains.Point22.Atlas\n"
        "open GaussianChains.Cert\n\n"
        "def scoreRows : List (ℕ × Interval) := [\n"
        + ",\n".join(rows)
        + "]\n\nend GaussianChains.Point22.Atlas\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().with_name("Point22AtlasScoreData.lean")
    text = generate()
    if args.write:
        with target.open("w", encoding="utf-8", newline="\n") as out:
            out.write(text)
    elif text != target.read_text(encoding="utf-8"):
        raise SystemExit("Width-22 score node data differ from the frozen verifier")
    print("Width-22 scalar-score nodes match the frozen verifier")
