"""Generate candidate strip trees. Every symbol in a tree must be checked in Lean.

The order of the closed-chamber, derivative and midpoint-score tests is the
one used in the frozen search. Unresolved leaves abort generation.
"""
import argparse
from collections import Counter
from fractions import Fraction
from itertools import combinations
import json
from pathlib import Path
import sys

inputs = argparse.ArgumentParser(add_help=False)
inputs.add_argument("--study", required=True, type=Path, help="frozen assembled study from reproduce.py setup")
CODE = inputs.parse_known_args()[0].study.resolve() / "code"
sys.path.insert(0, str(CODE))
from verify_six_site_global_reduction import BARY, DEN, PAIRS, Kernel, ceil_div, center_value, chamber, terms
from verify_six_site_width_band import WidthBand, perturbation
from verify_six_site_width_strip import width_errors

SLABS = [
    (Fraction("7.99"), Fraction(8), Fraction("8.01")),
    (Fraction(8), Fraction("8.25"), Fraction("8.5")),
    (Fraction("8.5"), Fraction("8.75"), Fraction(9)),
]
SUPPORTS = [
    a for count in range(1, 6) for a in combinations(range(5), count)
    if a != (2,) and a <= tuple(4 - k for k in reversed(a))
]
FLOORS = [
    list(range(DEN // 10, 36000, 600)) + [36000, 40200, 42000, 45000, DEN // 6],
    list(range(7 * DEN // 100, DEN // 6, DEN // 500)) + [DEN // 6],
]


def tree(band, support, target):
    cut = [[p for p, (i, j, _, _) in enumerate(PAIRS) if i <= k < j] for k in support]
    rays = [(k, 5, a) for k, a in zip(support, cut)]
    rays += [(k, j, sorted(set(a) ^ set(b))) for (k, a), (j, b) in combinations(zip(support, cut), 2)]
    stats = Counter()

    def visit(lo, hi):
        stats["nodes"] += 1
        if not chamber(lo, hi):
            stats["empty"] += 1
            return ["e"]
        lower, upper = terms(band, lo, hi, 1)
        grad = [(sum(lower[p] for p in a), sum(upper[p] for p in a)) for a in cut]
        for k, a in zip(support, cut):
            if sum(lower[p] for p in a) > 0 or sum(upper[p] for p in a) < 0:
                stats["gradient"] += 1
                return ["g", k]
        curv, _ = terms(band, lo, hi, 2)
        for k, j, a in rays:
            if sum(curv[p] for p in a) > 0:
                stats["curvature"] += 1
                return ["c", k, j]
        _, value, center = center_value(band, lo, hi, (lower, upper))
        gain = sum(max((hi[k]-center[k])*b, (lo[k]-center[k])*a, 0)
                   for k, (a, b) in zip(support, grad))
        if value + ceil_div(band.slack_hi*gain, DEN*BARY) < target:
            stats["value"] += 1
            return ["v", center]
        k = max(support, key=lambda i: hi[i] - lo[i])
        if hi[k] - lo[k] <= 1:
            raise ValueError(f"unresolved {support=} {lo=} {hi=}")
        mid = (lo[k] + hi[k]) // 2
        lhi, rlo = hi[:], lo[:]
        lhi[k], rlo[k] = mid, mid
        return ["s", k, mid, visit(lo, lhi), visit(rlo, hi)]

    initial = [BARY // 2 if i in support else 0 for i in range(5)] + [BARY]
    return visit([0] * 6, initial), dict(stats)


def postfix(node):
    tag, *args = node
    if tag == "s":
        k, cut, left, right = args
        yield from postfix(left)
        yield from postfix(right)
        yield f"4,{k},{cut}"
    elif tag == "v":
        yield ",".join(map(str, [3, *args[0]]))
    else:
        yield ",".join(map(str, [{"e": 0, "g": 1, "c": 2}[tag], *args]))


def lean_packet(directory, slab, path):
    """Width/floor/support are reconstructed by the checker from the row index."""
    records = []
    for band in range(len(FLOORS[int(slab != 0)]) - 1):
        for support in range(len(SUPPORTS)):
            packet = json.loads((directory/f"band-{slab}-{band:02}-{support:02}.json").read_text("ascii"))
            if (slab, band, support) != (packet["slab"], packet["floor"], packet["support"]):
                raise ValueError("packet index mismatch")
            code = ";".join(postfix(packet["tree"]))
            records.append(f'  ({packet["trial"]}, "{code}")')
    body = ["/-! Candidate trees for one width slab, generated by emit_band.py. -/",
            "namespace GaussianChains.Band", "",
            f"def slab{slab}Packets : Array (Nat × String) := #[",
            ",\n".join(records) + "]", "", "end GaussianChains.Band", ""]
    path.write_text("\n".join(body), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__, parents=[inputs])
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--slab", type=int, choices=range(3), required=True)
    parser.add_argument("--floor", type=int, action="append", help="zero-based floor band, repeatable")
    parser.add_argument("--support", type=int, choices=range(18), action="append")
    parser.add_argument("--lean", type=Path, help="also emit the full slab as a Lean packet table")
    args = parser.parse_args()
    l, a, r = SLABS[args.slab]
    errors = width_errors(l, a, r) if args.slab else perturbation()
    kernel = Kernel(exponent=a)
    edges = FLOORS[int(args.slab != 0)]
    output = args.output
    output.mkdir(parents=True, exist_ok=True)
    counts = Counter()
    for b in args.floor or range(len(edges) - 1):
        band = WidthBand(kernel, edges[b], edges[b+1], errors)
        trials = [[0, 0, j * (BARY//8), 0, 0, BARY-j*(BARY//8)] for j in range(5)]
        bounds = [center_value(band, u, u, terms(band, u, u, 1))[0]
                  - 2*len(PAIRS)*errors[0] for u in trials]
        j = max(range(5), key=bounds.__getitem__)
        for i in args.support or range(len(SUPPORTS)):
            root, stats = tree(band, SUPPORTS[i], bounds[j])
            record = dict(slab=args.slab, floor=b, support=i, trial=j, tree=root)
            name = output / f"band-{args.slab}-{b:02}-{i:02}.json"
            name.write_text(json.dumps(record, separators=(",", ":"))+"\n", encoding="ascii")
            counts.update(stats)
        band.get.cache_clear()
        band.at.cache_clear()
    print(dict(counts))
    if args.lean:
        lean_packet(output, args.slab, args.lean)


if __name__ == "__main__":
    main()
