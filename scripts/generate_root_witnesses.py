"""Regenerate the proposed rational input intervals for the ten Table 2 root brackets.

Usage: python scripts/generate_root_witnesses.py [--check]

All arithmetic here is rational. The Lean checker independently verifies that these
candidate intervals contain its own input enclosures and checks both endpoint signs.
"""

import argparse
from fractions import Fraction as F
from math import ceil, floor
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "formalization" / "PhaseStripRootsWitnesses.lean"
TRANSCRIPT = ROOT / "study" / "logs" / "certificates.txt"
PI_LO = F("3.14159265358979323846")
PI_HI = F("3.14159265358979323847")
WITNESS_SCALE = 10**24


def reduced_exp(arg):
    grid = 2**280
    z = -arg / 2**64
    cubic = 1 + z + z**2/2 + z**3/6
    lo = floor(max(0, cubic - z**4) * grid)
    hi = ceil((cubic + z**4) * grid)
    for _ in range(64):
        lo = lo*lo // grid
        hi = hi*hi // grid + 1
    return F(lo, grid), F(hi, grid)


def nome(width):
    return reduced_exp(PI_HI**2 / width)[0], reduced_exp(PI_LO**2 / width)[1]


def phase_cos(h):
    grid = 2**200
    a, b = 2*PI_LO*h / 2**20, 2*PI_HI*h / 2**20
    lo = floor((1-b**2/2+a**4/24-b**6/720) * grid)
    hi = ceil((1-a**2/2+b**4/24+b**6/720) * grid)
    for _ in range(20):
        lo = 2*max(0,lo)**2 // grid - grid
        hi = ceil(F(2*max(0,hi)**2, grid)) - grid
    return F(lo, grid), F(hi, grid)


def interval_text(bounds):
    lo, hi = bounds
    return f"gridBox {floor(lo*WITNESS_SCALE)} {ceil(hi*WITNESS_SCALE)}"


def generate():
    records = re.findall(r"^s=([\d/]+), h_([bc]) from \((\d+), (\d+)\) / 10\^17$",
                         TRANSCRIPT.read_text(encoding="utf-8"), re.M)
    if len(records) != 10 or len({(s, label) for s, label, _, _ in records}) != 10:
        raise ValueError("Expected ten distinct roots in the frozen certificate transcript")
    rows = []
    for width, label, left, right in records:
        numerator = int(left)
        if int(right) != numerator + 1:
            raise ValueError("Expected consecutive decimal endpoints")
        left_box, right_box = (phase_cos(F(k, 10**17)) for k in (numerator, numerator+1))
        outer = "true" if label == "b" else "false"
        width_label = {"8": "8", "33/4": "825", "17/2": "85", "35/4": "875", "9": "9"}[width]
        name = f"row{width_label}{'Contact' if label == 'b' else 'Center'}"
        row = (f"  ⟨{width}, {outer}, {numerator},\n"
                    f"   {interval_text(nome(F(width)))},\n"
                    f"   {interval_text(left_box)},\n"
                    f"   {interval_text(right_box)}⟩")
        rows.append((name, row))
    return """import CertTree

/-! Candidate Table 2 data generated by scripts/generate_root_witnesses.py.
PhaseStripRootsData checks all input enclosures and the endpoint signs in Lean. -/
namespace GaussianChains.PhaseStrip

open GaussianChains.Cert

structure RootRow where
  width : ℚ
  outer : Bool
  numerator : ℕ
  qBox : Interval
  xLeft : Interval
  xRight : Interval
  deriving Repr, DecidableEq

def RootRow.lower (r : RootRow) : ℚ := (r.numerator : ℚ) / 10^17
def RootRow.upper (r : RootRow) : ℚ := ((r.numerator : ℚ) + 1) / 10^17

private def gridBox (lo hi : ℤ) : Interval := ⟨(lo : ℚ)/10^24, (hi : ℚ)/10^24⟩

""" + "\n\n".join(f"def {name} : RootRow :=\n{row}" for name, row in rows) + (
        "\n\ndef rootRows : List RootRow :=\n  [" +
        ", ".join(name for name, _ in rows[:5]) + ",\n   " +
        ", ".join(name for name, _ in rows[5:]) + "]\n\nend GaussianChains.PhaseStrip\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the saved data without writing")
    args = parser.parse_args()
    source = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("Saved Table 2 data differ from the regenerated witnesses.")
        print("All ten Table 2 witness rows match.")
    else:
        OUTPUT.write_text(source, encoding="utf-8")
        print(OUTPUT)
